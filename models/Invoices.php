<?php

namespace app\models;

use Yii;

/**
 * This is the model class for table "invoices".
 *
 * @property int $id
 * @property string $invoiceno
 * @property double $amount
 * @property int $generated_by
 * @property string $status
 * @property string $paid_time
 * @property string $paid_through
 * @property string $payment_type
 * @property string $created_at
 * @property int $branch_id
 * @property int $customer_id
 *
 * @property Branch $branch
 * @property Customers $customer
 * @property User $generatedBy
 */
class Invoices extends \yii\db\ActiveRecord
{
    
    public $payment_option;
    
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'invoices';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['invoiceno', 'amount', 'generated_by', 'status', 'branch_id', 'customer_id'], 'required'],
            [['amount'], 'number'],
            [['generated_by', 'branch_id', 'customer_id'], 'integer'],
            [['paid_time', 'created_at'], 'safe'],
            [['invoiceno'], 'string', 'max' => 25],
            [['status', 'payment_type'], 'string', 'max' => 20],
            [['paid_through'], 'string', 'max' => 40],
            [['branch_id'], 'exist', 'skipOnError' => true, 'targetClass' => Branch::className(), 'targetAttribute' => ['branch_id' => 'id']],
            [['customer_id'], 'exist', 'skipOnError' => true, 'targetClass' => Customers::className(), 'targetAttribute' => ['customer_id' => 'id']],
            [['generated_by'], 'exist', 'skipOnError' => true, 'targetClass' => User::className(), 'targetAttribute' => ['generated_by' => 'id']],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => Yii::t('app', 'ID'),
            'invoiceno' => Yii::t('app', 'Invoiceno'),
            'amount' => Yii::t('app', 'Amount'),
            'generated_by' => Yii::t('app', 'Generated By'),
            'status' => Yii::t('app', 'Status'),
            'paid_time' => Yii::t('app', 'Paid Time'),
            'paid_through' => Yii::t('app', 'Paid Through'),
            'payment_type' => Yii::t('app', 'Payment Type'),
            'created_at' => Yii::t('app', 'Created At'),
            'branch_id' => Yii::t('app', 'Branch Name'),
            'customer_id' => Yii::t('app', 'Customer Name'),
        ];
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getBranch()
    {
        return $this->hasOne(Branch::className(), ['id' => 'branch_id']);
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getCustomer()
    {
        return $this->hasOne(Customers::className(), ['id' => 'customer_id']);
    }

    /**
     * @return \yii\db\ActiveQuery
     */
    public function getGeneratedBy()
    {
        return $this->hasOne(User::className(), ['id' => 'generated_by']);
    }
}
